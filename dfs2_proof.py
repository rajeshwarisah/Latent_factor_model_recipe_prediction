    print("DFS1: Calculate R(0)")
    print("-" * 70)
    print("From node 0:")
    print("  To reach 1: use 0→1 (cost 0)")
    print("  To reach 2: use 0→2 (cost 0)")
    print("  To reach 3: use 0→1→3 (costs 0+0)")
    print()
    print("R(0) = 0")
    print()

    print("DFS2: Calculate for all nodes")
    print("-" * 70)
    print()

    result = [0, 0, 0, 0]

    print("Start at node 0, R(0) = 0")
    print()

    print("Visit neighbor 1 from node 0:")
    print("  Edge: 0 → 1 (cost = 0)")
    print("  Interpretation:")
    print("    - From node 0's perspective, edge points TO child 1")
    print("    - When node 1 becomes root, this edge points AWAY from 1")
    print("    - Need to reverse it!")
    print("  Formula: R(1) = R(0) + (1 if cost==0 else -1)")
    print("          R(1) = 0 + 1 = 1")
    print()

    result[1] = result[0] + 1

    print("  Now at node 1, R(1) = 1")
    print("  Visit neighbor 3 from node 1:")
    print("    Edge: 1 → 3 (cost = 0)")
    print("    R(3) = R(1) + 1 = 1 + 1 = 2")
    print()

    result[3] = result[1] + 1

    print("Visit neighbor 2 from node 0:")
    print("  Edge: 0 → 2 (cost = 0)")
    print("  R(2) = R(0) + 1 = 0 + 1 = 1")
    print()

    result[2] = result[0] + 1

    print(f"Final result: {result}")
    print()

    print("Verification:")
    print("-" * 70)
    print("R(0) = 0: 0→1, 0→2, 0→1→3 (no reversals) ✓")
    print("R(1) = 1: 1→0 (rev), 1→0→2, 1→3 (1 reversal) ✓")
    print("R(2) = 1: 2→0 (rev), 2→0→1, 2→0→1→3 (1 reversal) ✓")
    print("R(3) = 2: 3→1 (rev), 3→1→0 (rev), 3→1→0→2 (2 reversals) ✓")
    print()


