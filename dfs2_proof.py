def mathematical_proof():
    """Mathematical proof of the formula"""
    print("="*70)
    print("MATHEMATICAL PROOF")
    print("="*70)
    print()

    print("Notation:")
    print("-" * 70)
    print("  R(v) = minimum reversals needed when node v is the root")
    print("  E = set of all edges")
    print("  For edge (u, v):")
    print("    - rev(u→v, root) = 1 if edge needs reversal from root, else 0")
    print()

    print("Key Observation:")
    print("-" * 70)
    print("  R(v) = Σ rev(e, v) for all edges e")
    print("       = count of edges that point away from v")
    print()

    print("When moving root from parent P to child C:")
    print("-" * 70)
    print()
    print("ALL edges except the edge between P and C remain the same!")
    print()
    print("Why?")
    print("  - For any other edge (u, v):")
    print("    * If it pointed toward P, it now points toward C (via P)")
    print("    * If it pointed away from P, it points away from C (via P)")
    print("    * The reversal requirement doesn't change!")
    print()

    print("ONLY the edge between P and C changes:")
    print()

    print("Case 1: Edge is P → C (cost = 0)")
    print("-" * 70)
    print("  When P is root:")
    print("    Edge P → C points away from P toward C")
    print("    No reversal needed: rev(P→C, P) = 0")
    print()
    print("  When C is root:")
    print("    Edge P → C points away from C toward P")
    print("    Reversal needed: rev(P→C, C) = 1")
    print()
    print("  Change = rev(P→C, C) - rev(P→C, P) = 1 - 0 = +1")
    print()

    print("Case 2: Edge is C → P (cost = 1)")
    print("-" * 70)
    print("  When P is root:")
    print("    Edge C → P points toward P")
    print("    Reversal needed: rev(C→P, P) = 1")
    print()
    print("  When C is root:")
    print("    Edge C → P points away from C")
    print("    No reversal needed: rev(C→P, C) = 0")
    print()
    print("  Change = rev(C→P, C) - rev(C→P, P) = 0 - 1 = -1")
    print()

    print("Therefore:")
    print("-" * 70)
    print("  R(C) = R(P) + change")
    print("       = R(P) + (1 if edge is P→C else -1)")
    print("       = R(P) + (1 if cost == 0 else -1)")
    print()
    print("QED ✓")
    print()


def detailed_example():
    """Detailed walkthrough with tracking"""
