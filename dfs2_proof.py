def prove_correctness():
    """Formal correctness proof"""
    print("="*70)
    print("FORMAL CORRECTNESS PROOF")
    print("="*70)
    print()

    print("Theorem:")
    print("-" * 70)
    print("Given a tree with directed edges, for any parent-child pair (P, C):")
    print()
    print("  R(C) = R(P) + Δ")
    print()
    print("where Δ = +1 if edge is P→C, and Δ = -1 if edge is C→P")
    print()

    print("Proof:")
    print("-" * 70)
    print()
    print("Let E be the set of all edges in the tree.")
    print("Partition E into three sets:")
    print("  - E_pc: edge between P and C")
    print("  - E_other: all other edges")
    print()
    print("For any root r:")
    print("  R(r) = Σ_{e ∈ E} rev(e, r)")
    print()
    print("Key Lemma: For any edge e ∈ E_other:")
    print("  rev(e, P) = rev(e, C)")
    print()
    print("Proof of Lemma:")
    print("  Consider edge (u, v) where u, v ≠ {P, C}")
    print()
    print("  Case 1: u and v are both in subtree rooted at C")
    print("    - Path from P: P → ... → C → ... → u/v")
    print("    - Path from C: C → ... → u/v")
    print("    - Relative position of u, v unchanged")
    print("    - rev(u→v, P) = rev(u→v, C)")
    print()
    print("  Case 2: u and v are both outside C's subtree")
    print("    - Path from P: P → ... → u/v")
    print("    - Path from C: C → P → ... → u/v")
    print("    - Both go through P to reach u, v")
    print("    - Relative position unchanged")
    print("    - rev(u→v, P) = rev(u→v, C)")
    print()
    print("  Case 3: One in subtree, one outside")
    print("    - Both paths must cross P-C edge")
    print("    - Same relative orientation")
    print("    - rev(u→v, P) = rev(u→v, C)")
    print()
    print("Therefore:")
    print("  R(C) = Σ_{e ∈ E_other} rev(e, C) + rev(P-C edge, C)")
    print("       = Σ_{e ∈ E_other} rev(e, P) + rev(P-C edge, C)")
    print()
    print("  R(P) = Σ_{e ∈ E_other} rev(e, P) + rev(P-C edge, P)")
    print()
    print("  R(C) - R(P) = rev(P-C edge, C) - rev(P-C edge, P)")
    print()
    print("If edge is P→C:")
    print("  rev(P→C, C) = 1 (points away from C)")
    print("  rev(P→C, P) = 0 (points away from P toward C)")
    print("  Δ = 1 - 0 = +1")
    print()
    print("If edge is C→P:")
    print("  rev(C→P, C) = 0 (points away from C)")
    print("  rev(C→P, P) = 1 (points toward P)")
    print("  Δ = 0 - 1 = -1")
    print()
    print("∴ R(C) = R(P) + Δ")
    print()
    print("QED ✓")
    print()


